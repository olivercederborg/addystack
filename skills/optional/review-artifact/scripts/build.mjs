#!/usr/bin/env node
// Builds a review artifact from its two sources in <dir>:
//   body.html  the page inside <main>: running head, hero, specs, optional ruler, one section
//              per changed behavior, Decisions, Verified, Not verified, and one fold
//   llms.md    the same review as Markdown, for AI reviewers
//   extra.css  optional: placement for this page's figures, using the template's tokens only
// and writes:
//   index.html standalone page, fonts inlined, with a footer linking llms.md and the font notice
//   capsule/   a Lakebed capsule serving the page at / and the Markdown at /llms.md
// Usage: node build.mjs <dir> [--name <capsule-name>]
import { cpSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const assets = fileURLToPath(new URL("../assets/", import.meta.url));
const args = process.argv.slice(2);
const dir = args.find((a, i) => !a.startsWith("--") && args[i - 1] !== "--name");
if (!dir) {
  console.error("usage: node build.mjs <dir> [--name <capsule-name>]");
  process.exit(2);
}
const read = (file) => readFileSync(join(dir, file), "utf8");
for (const file of ["body.html", "llms.md"]) {
  if (!existsSync(join(dir, file))) {
    console.error(`missing ${join(dir, file)}: start from ${join(assets, "example", file)}`);
    process.exit(2);
  }
}

const NOTICE =
  'Set in Geist and Geist Mono, © 2024 The Geist Project Authors, <a href="https://openfontlicense.org">SIL Open Font License 1.1</a>.';
const plain = (html) =>
  html.replace(/<[^>]+>/g, "").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&amp;/g, "&").replace(/\s+/g, " ").trim();

let body = read("body.html").trim();
const h1 = body.match(/<h1[^>]*>([\s\S]*?)<\/h1>/);
const verdict = body.match(/<p class="verdict"><strong>([\s\S]*?)<\/strong>/);
if (!h1 || !verdict) {
  console.error("body.html needs an <h1> and a <p class=\"verdict\"><strong>…</strong> sentence in its header");
  process.exit(1);
}
const title = plain(h1[1]);
const prs = [...new Set([...body.matchAll(/>#(\d+)</g)].map((m) => `#${m[1]}`))];
const pageTitle = prs.length ? `${title} — ${prs.join(", ")}` : title;
if (!body.includes("</details>")) {
  console.error("body.html needs its fold: one <details> at the end");
  process.exit(1);
}
body = `${body}\n<footer class="foot"><a href="llms.md">llms.md</a><p class="notice">${NOTICE}</p></footer>`;

const font = (family, file) =>
  `@font-face { font-family: "${family}"; src: url(data:font/woff2;base64,${readFileSync(join(assets, "fonts", file)).toString("base64")}) format("woff2"); font-weight: 100 900; font-display: block; }`;
const extra = existsSync(join(dir, "extra.css")) ? `\n/* extra.css */\n${read("extra.css")}` : "";
const css = [
  "/* Geist and Geist Mono: © 2024 The Geist Project Authors (https://github.com/vercel/geist-font), SIL Open Font License 1.1 (https://openfontlicense.org). Unmodified upstream files. */",
  font("Geist", "Geist[wght].woff2"),
  font("Geist Mono", "GeistMono[wght].woff2"),
  "",
  readFileSync(join(assets, "page.css"), "utf8"),
].join("\n") + extra;
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;");

writeFileSync(
  join(dir, "index.html"),
  `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="light dark">
<title>${esc(pageTitle)}</title>
<link rel="alternate" type="text/markdown" href="llms.md">
<style>
${css}
</style>
</head>
<body>
<main>
${body}
</main>
</body>
</html>
`,
);

const flag = args.indexOf("--name");
const slug = title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const name = flag >= 0 ? args[flag + 1] : `review-${slug}`.slice(0, 48).replace(/-$/, "");
const capsule = join(dir, "capsule");
for (const part of ["client", "server", "scripts"]) cpSync(join(assets, "capsule", part), join(capsule, part), { recursive: true });
mkdirSync(join(capsule, "shared"), { recursive: true });
const js = JSON.stringify;
const llms = read("llms.md");
const llmsTxt = `# ${title}\n\nReview artifact${prs.length ? ` for ${prs.join(" and ")}` : ""}.\n\n- [Review as Markdown](/llms.md)\n`;
writeFileSync(
  join(capsule, "shared", "page.ts"),
  `// Generated by review-artifact's build.mjs from body.html; edit that file, then rebuild.\nexport const TITLE = ${js(pageTitle)};\nexport const CSS = ${js(css)};\nexport const BODY = ${js(body)};\n`,
);
writeFileSync(
  join(capsule, "shared", "llms.ts"),
  `// Generated by review-artifact's build.mjs from llms.md; edit that file, then rebuild.\nexport const NAME = ${js(name)};\nexport const LLMS = ${js(llms)};\nexport const LLMS_TXT = ${js(llmsTxt)};\n`,
);
writeFileSync(join(capsule, "scripts", "markers.json"), `${js({ title, verdict: plain(verdict[1]) })}\n`);

console.log(`built ${resolve(dir, "index.html")}`);
console.log(`built ${resolve(capsule)} (capsule name ${name}; ${basename(dir)})`);
